"""Synthetic match simulator (BRD §7.2).

Plays out a full 90-minute match as a sequence of possession chains. Between
storyline beats, play is generated by a simple probabilistic model of passes,
long balls, crosses, carries, pressure, tackles, shots and set pieces, tuned to
real match statistics (see calibration.py and reference.py). Player positions
are moved every second towards formation anchors that shift with the ball, plus
off-ball support runs, which yields 1 Hz tracking frames for distance and speed
metrics.

The simulator is deterministic for a given seed and storyline.
"""

from __future__ import annotations

import math
import random
from dataclasses import dataclass, field
from typing import TYPE_CHECKING

from matchlens.domain.models import (
    PITCH_LENGTH,
    PITCH_WIDTH,
    EntityPosition,
    Event,
    EventType,
    MatchMeta,
    Outcome,
    Position,
    SyntheticMatch,
    TrackingFrame,
)
from matchlens.domain.pitch import (
    ANCHORS,
    clamp_point,
    distance,
    expected_goals,
    goal_distance_and_angle,
    point_to_segment_distance,
    to_absolute,
    to_relative,
)
from matchlens.simulator.roster import default_match_meta
from matchlens.simulator.storyline import Beat, BeatType, Storyline, comeback_storyline
from matchlens.simulator.style import NEUTRAL, SimStyle

if TYPE_CHECKING:
    from matchlens.simulator.fork import RolloutTrace, SimSnapshot
    from matchlens.simulator.intent_exec import IntentController

HALF_LENGTH = 2700.0
CENTRE = (PITCH_LENGTH / 2, PITCH_WIDTH / 2)

Vec = tuple[float, float]

# Roles whose players move with the defensive line (SimStyle.line_height).
_DEFENCE_ROLES = frozenset({"LB", "LCB", "RCB", "RB", "CB", "LWB", "RWB"})


class _Stop(Exception):
    """Ends a rollout early; ``terminal`` says why (goal, shot, turnover, restart:<kind>, horizon)."""

    def __init__(self, terminal: str) -> None:
        super().__init__(terminal)
        self.terminal = terminal


@dataclass
class _Scheduled:
    beat: Beat
    period: int
    clock: float


@dataclass
class _State:
    period: int = 1
    clock: float = 0.0
    elapsed: float = 0.0
    possession: str = ""  # team_id
    carrier: str = ""  # player_id
    ball: Vec = CENTRE
    score: dict[str, int] = field(default_factory=dict)
    on_pitch: dict[str, list[str]] = field(default_factory=dict)  # team -> player_ids
    roles: dict[str, str] = field(default_factory=dict)  # player_id -> anchor role
    booked: set[str] = field(default_factory=set)
    sent_off: set[str] = field(default_factory=set)
    positions: dict[str, Vec] = field(default_factory=dict)
    # Run-to overrides: a player keeps running to this point until reached.
    targets: dict[str, Vec] = field(default_factory=dict)
    next_frame: float = 0.0


class MatchSimulator:
    def __init__(
        self,
        seed: int = 7,
        meta: MatchMeta | None = None,
        storyline: Storyline | None = None,
        *,
        styles: dict[str, SimStyle] | None = None,
        intent: IntentController | None = None,
        frame_dt: float = 1.0,
        id_prefix: str = "",
    ) -> None:
        self.seed = seed
        self.rng = random.Random(seed)
        self.storyline = storyline if storyline is not None else comeback_storyline()
        self.meta = meta or default_match_meta(storyline_title=self.storyline.title)
        self.events: list[Event] = []
        self.tracking: list[TrackingFrame] = []
        self.s = _State()
        self._seq = 0
        self._wander = {pid: (self.rng.uniform(0, 2 * math.pi), self.rng.uniform(25, 60))
                        for pid in self.meta.players}
        self._pending_corrections: list[tuple[float, Event, str]] = []
        # Playing style per team, an optional tactic intent and fork settings. All of
        # these are inert by default, so run() output is identical to a plain simulator.
        self._styles = dict(styles) if styles else {}
        self._intent = intent
        self._frame_dt = frame_dt  # seconds between tracking frames (1.0 = the 1 Hz match feed)
        self._id_prefix = id_prefix
        self._stop_at: float | None = None  # rollout horizon (elapsed seconds); None outside rollouts
        self._pending_terminal: str | None = None  # set once a shot is taken in a rollout
        self._counter_until: dict[str, float] = {}  # team -> end of its counter-attack window
        self._last_frame_t: float | None = None
        self._team_by_player = {
            pid: team.team_id for team in (self.meta.home, self.meta.away) for pid in team.starting_xi + team.bench
        }

    # ------------------------------------------------------------------ setup

    def _style(self, team_id: str) -> SimStyle:
        style = self._styles.get(team_id, NEUTRAL)
        if self._intent is not None:
            style = self._intent.adjust_style(team_id, style)
        return style

    def _team_ids(self) -> tuple[str, str]:
        return self.meta.home.team_id, self.meta.away.team_id

    def _attacks_right(self, team_id: str) -> bool:
        return team_id == self.meta.home.team_id

    def _opp(self, team_id: str) -> str:
        return self.meta.opponent(team_id).team_id

    def _team_of(self, player_id: str) -> str:
        return self._team_by_player.get(player_id) or player_id.split("-")[0]

    def _setup(self) -> None:
        s = self.s
        for team in (self.meta.home, self.meta.away):
            s.score[team.team_id] = 0
            s.on_pitch[team.team_id] = list(team.starting_xi)
            for pid in team.starting_xi:
                s.roles[pid] = self.meta.players[pid].role
        self._reset_positions()

    def _anchor_abs(self, pid: str, in_possession: bool) -> Vec:
        team = self._team_of(pid)
        right = self._attacks_right(team)
        ax, ay = ANCHORS[self.s.roles[pid]]
        bx, by = to_relative(*self.s.ball, right)
        style = self._style(team)
        if self.s.roles[pid] == "GK":
            x = ax + max(0.0, (bx - 35) * 0.12)
            y = 34 + (by - 34) * 0.15
        else:
            shift = (bx - 45) * 0.55 + 5 if in_possession else (bx - 52.5) * 0.5 - 5 + style.block_height
            width = 1.0 * style.width_in_poss if in_possession else 0.78 * style.compactness_out
            if self.s.roles[pid] in _DEFENCE_ROLES:
                shift += style.line_height
            x = ax + shift
            y = 34 + (ay - 34) * width + (by - 34) * 0.3
            phase, period = self._wander[pid]
            x += 3 * math.sin(self.s.elapsed / period + phase)
            y += 2.5 * math.cos(self.s.elapsed / (period * 0.8) + phase)
        x = min(max(x, 1.0), PITCH_LENGTH - 1)
        y = min(max(y, 1.0), PITCH_WIDTH - 1)
        point = to_absolute(x, y, right)
        if self._intent is not None:
            point = self._intent.override(pid, self.s, point) or point
        return point

    def _kickoff_positions(self) -> dict[str, Vec]:
        saved_ball, self.s.ball = self.s.ball, CENTRE
        out: dict[str, Vec] = {}
        for team, pids in self.s.on_pitch.items():
            for pid in pids:
                x, y = self._anchor_abs(pid, in_possession=False)
                # Kick-off shape: everyone in their own half.
                x = min(x, 51.0) if self._attacks_right(team) else max(x, 54.0)
                out[pid] = (x, y)
        self.s.ball = saved_ball
        return out

    def _reset_positions(self) -> None:
        self.s.ball = CENTRE
        self.s.targets.clear()
        self.s.positions.update(self._kickoff_positions())

    # -------------------------------------------------------------- emitting

    def _emit(self, type_: EventType, **kw: object) -> Event:
        self._seq += 1
        start = kw.pop("start", None)
        end = kw.pop("end", None)
        ev = Event(
            event_id=f"{self._id_prefix}{self.meta.match_id}-e{self._seq:05d}",
            match_id=self.meta.match_id,
            sequence=self._seq,
            period=self.s.period,
            clock=round(self.s.clock, 1),
            elapsed=round(self.s.elapsed, 1),
            type=type_,
            start=clamp_point(*start) if start else None,  # type: ignore[misc]
            end=clamp_point(*end) if end else None,  # type: ignore[misc]
            **kw,  # type: ignore[arg-type]
        )
        self.events.append(ev)
        return ev

    # --------------------------------------------------------------- timing

    def _advance(self, dt: float, ball_to: Vec | None = None, chasers: tuple[str, ...] = ()) -> None:
        """Advance time by dt seconds, moving the ball linearly to ball_to and
        emitting tracking frames (1 Hz, or every ``frame_dt`` seconds in a fork)."""
        s = self.s
        start_elapsed = s.elapsed
        ball_from = s.ball
        target_ball = ball_to or s.ball
        end_elapsed = start_elapsed + dt
        while s.next_frame <= end_elapsed:
            if self._stop_at is not None and s.next_frame > self._stop_at + 1e-9:
                raise _Stop(self._pending_terminal or "horizon")
            frac = 1.0 if dt == 0 else (s.next_frame - start_elapsed) / dt
            frac = min(max(frac, 0.0), 1.0)
            s.ball = (
                ball_from[0] + (target_ball[0] - ball_from[0]) * frac,
                ball_from[1] + (target_ball[1] - ball_from[1]) * frac,
            )
            s.clock += s.next_frame - s.elapsed
            s.elapsed = s.next_frame
            self._move_players(chasers)
            self._frame()
            s.next_frame = s.next_frame + 1.0 if self._frame_dt == 1.0 else round(s.next_frame + self._frame_dt, 6)
        s.clock += end_elapsed - s.elapsed
        s.elapsed = end_elapsed
        s.ball = target_ball
        self._flush_corrections()

    def _move_players(self, chasers: tuple[str, ...]) -> None:
        s = self.s
        new_positions: dict[str, Vec] = {}
        smooth = self._frame_dt != 1.0
        for team, pids in s.on_pitch.items():
            in_poss = team == s.possession
            for pid in pids:
                px, py = s.positions.get(pid, self._anchor_abs(pid, in_poss))
                top = self.meta.players[pid].top_speed
                if pid in s.targets:
                    tx, ty = s.targets[pid]
                    cap, lag = top * 0.95, 1.0
                elif pid in chasers or pid == s.carrier:
                    tx, ty = s.ball
                    cap, lag = top * 0.95, 0.85
                else:
                    tx, ty = self._anchor_abs(pid, in_poss)
                    cap, lag = top * 0.6, 0.35
                    if self._intent is not None and self._intent.is_sprinting(pid, s.elapsed):
                        cap, lag = top * 0.95, 0.6  # a directed run
                if smooth:
                    # Per-frame limits scale with the frame interval; lag compounds per second.
                    cap, lag = cap * self._frame_dt, 1 - (1 - lag) ** self._frame_dt
                dx, dy = tx - px, ty - py
                d = math.hypot(dx, dy)
                step = min(d * lag, cap)
                if d > 0:
                    px += dx / d * step
                    py += dy / d * step
                if pid in s.targets and d - step < 1.0:
                    del s.targets[pid]
                new_positions[pid] = (px, py)
        # Keep ids of players no longer on the pitch out of the state.
        s.positions = new_positions

    def _frame(self) -> None:
        s = self.s
        entities = [EntityPosition(entity_id="ball", x=round(s.ball[0], 2), y=round(s.ball[1], 2), speed=0.0)]
        prev = self.tracking[-1] if self.tracking else None
        prev_pos = {e.entity_id: (e.x, e.y) for e in prev.entities} if prev and prev.period == s.period else {}
        # Speed is metres per second whatever the frame interval; the first frame of a
        # fork may follow a longer gap than frame_dt.
        gap = self._frame_dt
        if self._frame_dt != 1.0 and self._last_frame_t is not None:
            gap = max(s.elapsed - self._last_frame_t, self._frame_dt)
        self._last_frame_t = s.elapsed
        for pid, (x, y) in s.positions.items():
            speed = distance((x, y), prev_pos[pid]) / gap if pid in prev_pos else 0.0
            entities.append(EntityPosition(entity_id=pid, x=round(x, 2), y=round(y, 2), speed=round(speed, 2)))
        if "ball" in prev_pos:
            entities[0] = entities[0].model_copy(update={"speed": round(distance(s.ball, prev_pos["ball"]) / gap, 2)})
        self.tracking.append(
            TrackingFrame(
                match_id=self.meta.match_id,
                clock=round(s.clock, 1),
                elapsed=round(s.elapsed, 1),
                period=s.period,
                entities=entities,
            )
        )

    def _flush_corrections(self) -> None:
        due = [c for c in self._pending_corrections if c[0] <= self.s.elapsed]
        for item in due:
            self._pending_corrections.remove(item)
            _, target, correct_player = item
            self._emit(
                EventType.CORRECTION,
                team_id=target.team_id,
                player_id=correct_player,
                corrects_event_id=target.event_id,
                attrs={"field": "player_id", "previous": target.player_id or "", "value": correct_player},
            )

    # -------------------------------------------------------------- helpers

    def _rel(self, team: str, p: Vec) -> Vec:
        return to_relative(p[0], p[1], self._attacks_right(team))

    def _abs(self, team: str, p: Vec) -> Vec:
        return to_absolute(p[0], p[1], self._attacks_right(team))

    def _nearest(self, team: str, point: Vec, exclude: str | None = None) -> tuple[str, float]:
        best, best_d = "", float("inf")
        for pid in self.s.on_pitch[team]:
            if pid == exclude:
                continue
            d = distance(self.s.positions[pid], point)
            if d < best_d:
                best, best_d = pid, d
        return best, best_d

    def _dominance(self, team: str) -> float:
        minute = self.s.clock / 60
        dom = self.storyline.dominance_at(minute)
        if team != self.meta.home.team_id:
            dom = -dom
        diff = len(self.s.on_pitch[team]) - len(self.s.on_pitch[self._opp(team)])
        return max(-1.0, min(1.0, dom + 0.2 * diff))

    def _change_possession(self, team: str, carrier: str, reason: str) -> None:
        self.s.possession = team
        self.s.carrier = carrier
        self._emit(
            EventType.POSSESSION_CHANGE,
            team_id=team,
            player_id=carrier,
            start=self.s.ball,
            attrs={"reason": reason},
        )
        if reason in ("tackle", "interception"):
            style = self._style(team)
            if style.counter_boost > 0:
                self._counter_until[team] = self.s.elapsed + style.counter_window_s
        self._rollout_end("turnover")

    def _rollout_end(self, terminal: str) -> None:
        """Ends a rollout at a natural stopping point; a no-op in a full match."""
        if self._stop_at is not None:
            raise _Stop(terminal)

    def _player_by_role(self, team: str, roles: tuple[str, ...]) -> str:
        for pid in self.s.on_pitch[team]:
            if self.s.roles[pid] in roles:
                return pid
        return self.rng.choice(self.s.on_pitch[team])

    # ------------------------------------------------------------ open play

    def _step(self) -> None:
        s = self.s
        team, carrier = s.possession, s.carrier
        opp = self._opp(team)
        dom = self._dominance(team)
        bx, by = self._rel(team, s.ball)

        presser, pd = self._nearest(opp, s.ball)
        press = self._style(opp).press_intensity
        pressured = False
        if pd < 6 * press and self.rng.random() < 0.8 * press:
            pressured = True
            self._emit(
                EventType.PRESSURE,
                team_id=opp,
                player_id=presser,
                related_player_id=carrier,
                start=s.positions[presser],
                attrs={"distance_m": round(pd, 1)},
            )
            self._advance(0.6, chasers=(presser,))
            roll = self.rng.random()
            if roll < 0.105:
                self._foul(presser, carrier)
                return
            if roll < 0.105 + max(0.04, 0.1 - 0.05 * dom) * press**0.5:
                self._emit(
                    EventType.TACKLE,
                    team_id=opp,
                    player_id=presser,
                    related_player_id=carrier,
                    start=s.ball,
                    outcome=Outcome.SUCCESS,
                )
                self._change_possession(opp, presser, "tackle")
                self._advance(1.5)
                return

        if self._intent is not None and self._follow_ball_plan(team, carrier, pressured, (bx, by)):
            return

        style = self._style(team)
        goal_dist, angle = goal_distance_and_angle(bx, by)
        if goal_dist < 30 and angle > 0.12:
            in_box = bx >= PITCH_LENGTH - 16.5 and abs(by - PITCH_WIDTH / 2) <= 20.16
            p_shot = (0.3 + 0.5 * ((20 - min(goal_dist, 20)) / 20) ** 2 if in_box else 0.09) * (1 + 0.5 * dom)
            if self.rng.random() < p_shot * style.shot_appetite:
                self._shot(carrier, (bx, by))
                return

        if bx > 75 and abs(by - PITCH_WIDTH / 2) > 16 and self.rng.random() < 0.3 * style.crossing:
            self._cross(carrier, pressured)
        elif self.rng.random() < (0.3 if bx > 70 else 0.16) * style.dribbling and bx < 95:
            self._carry(carrier, pressured)
        else:
            self._pass(carrier, pressured)

    def _follow_ball_plan(self, team: str, carrier: str, pressured: bool, rel: Vec) -> bool:
        """Carry out the active ball-plan step of a tactic intent. Returns True when it acted. The step
        stays active while the action runs (pass_bias reads it) and is consumed afterwards."""
        assert self._intent is not None
        step = self._intent.active_step(team, carrier)
        if step is None:
            return False
        action = str(step.action)
        bx, by = rel
        if action == "shoot":
            goal_dist, angle = goal_distance_and_angle(bx, by)
            if goal_dist < 32 and angle > 0.1:
                self._shot(carrier, (bx, by))
            elif bx < 95:
                self._carry(carrier, pressured)  # work the ball into range first
                return True
            else:
                return False
        elif action == "cross":
            if bx <= 60:
                self._carry(carrier, pressured)
                return True
            self._cross(carrier, pressured)
        elif action == "carry":
            self._carry(carrier, pressured)
        elif action in ("long_ball", "switch", "cutback"):
            self._pass(carrier, pressured, plan=action)
        else:
            self._pass(carrier, pressured)
        self._intent.consume()
        return True

    def _pass_candidates(self, team: str, carrier: str) -> list[tuple[str, float, float, int, Vec]]:
        """Return (receiver, weight, distance, lane opponents, rel position)."""
        opp = self._opp(team)
        b_abs = self.s.ball
        bx, _ = self._rel(team, b_abs)
        style = self._style(team)
        verticality = style.verticality
        if self.s.elapsed < self._counter_until.get(team, -1.0):
            verticality += style.counter_boost  # quick break after a regain
        out = []
        for pid in self.s.on_pitch[team]:
            if pid == carrier:
                continue
            r_abs = self.s.positions[pid]
            rx, ry = self._rel(team, r_abs)
            d = distance(b_abs, r_abs)
            forward = rx - bx
            _, openness = self._nearest(opp, r_abs)
            lane = sum(
                1
                for o in self.s.on_pitch[opp]
                if point_to_segment_distance(self.s.positions[o], b_abs, r_abs) < 2.5
            )
            position = self.meta.players[pid].position
            # Recycle possession through defenders and midfielders; only
            # reward forward passes strongly once the move is building.
            fwd_weight = (0.035 if bx < 70 else 0.012) * verticality
            score = (
                fwd_weight * max(-25.0, min(forward, 35.0))
                - 0.07 * max(0.0, d - 12)
                + 0.2 * min(openness, 8)
                - 0.75 * lane
                - (1.0 if d < 5 else 0.0)
                + (0.55 if position in (Position.DEF, Position.MID) else 0.0)
                - (0.6 if position == Position.FWD and rx > 85 else 0.0)
                - (1.5 if self.s.roles[pid] == "GK" and bx > 30 else 0.0)
            )
            if self._intent is not None:
                score += self._intent.pass_bias(team, carrier, pid, r_abs)
            out.append((pid, math.exp(score * 1.1), d, lane, (rx, ry)))
        return out

    def _long_ball_chance(self, bx: float, pressured: bool, set_piece: str | None) -> float:
        """How often a long ball is played instead of a pass to feet."""
        directness = self._style(self.s.possession).directness
        if set_piece == "goal_kick":
            return 0.5 * directness
        if set_piece == "free_kick":
            return (0.5 if bx < 60 else 0.3) * directness
        if bx < 35:
            return (0.3 if pressured else 0.07) * directness
        return (0.08 if pressured else 0.04) * directness

    def _pass(self, carrier: str, pressured: bool, set_piece: str | None = None, plan: str | None = None) -> None:
        """``plan`` (long_ball, switch, cutback) is a ball-plan step from a tactic intent."""
        s = self.s
        team = s.possession
        opp = self._opp(team)
        cands = self._pass_candidates(team, carrier)
        if not cands:
            return
        bx, by = self._rel(team, s.ball)
        long_cands = [c for c in cands if c[2] > 30 and c[4][0] > bx - 5]
        if plan == "long_ball":
            cands = long_cands or cands
        elif plan == "switch":
            cands = [c for c in cands if abs(c[4][1] - by) > 22] or cands
        elif long_cands and self.rng.random() < self._long_ball_chance(bx, pressured, set_piece):
            cands = long_cands
        receiver, _, d, lane, (rx, ry) = self.rng.choices(cands, weights=[c[1] for c in cands])[0]
        start = s.ball
        target = s.positions[receiver]
        if 9 < d <= 30 and not set_piece:
            # The receiver comes towards the ball to take it.
            f = self.rng.uniform(0.05, 0.5)
            target = (target[0] + (start[0] - target[0]) * f, target[1] + (start[1] - target[1]) * f)
            d = distance(start, target)
            rx, ry = self._rel(team, target)
        forward = rx - bx
        _, openness = self._nearest(opp, s.positions[receiver])
        dom = self._dominance(team)
        p = (
            0.95
            - 0.003 * d
            - 0.032 * max(0.0, d - 22)
            - (0.09 if pressured else 0.0)
            - 0.06 * lane
            - 0.003 * max(0.0, forward)
            - (0.07 if rx > 88 else 0.0)
            + 0.008 * min(openness, 6)
            + 0.05 * dom
        )
        p = min(max(p, 0.2), 0.99)
        lofted = d > 30 or set_piece == "corner"
        speed_kmh = round(min(max(24 + 1.45 * d + self.rng.gauss(0, 6), 18), 110), 1)
        travel = d / (speed_kmh / 3.6 * (0.7 if lofted else 0.85))
        attrs: dict[str, float | int | str | bool] = {
            "ball_speed_kmh": speed_kmh,
            "height": "high" if lofted else "ground",
            "pressured": pressured,
        }
        if set_piece:
            attrs["set_piece"] = set_piece
        if plan:
            attrs["plan"] = plan
        if self.rng.random() < p:
            end = (target[0] + self.rng.gauss(0, 0.6), target[1] + self.rng.gauss(0, 0.6))
            self._emit(
                EventType.PASS,
                team_id=team,
                player_id=carrier,
                related_player_id=receiver,
                start=start,
                end=end,
                outcome=Outcome.SUCCESS,
                attrs=attrs,
            )
            s.carrier = receiver
            for _ in range(2):
                self._support_run(team, receiver)
            self._advance(travel + self.rng.uniform(1.0, 2.4) / self._style(team).tempo, ball_to=end,
                          chasers=(receiver,))
            return

        frac = self.rng.uniform(0.55, 1.15)
        end = (
            start[0] + (target[0] - start[0]) * frac + self.rng.gauss(0, 3),
            start[1] + (target[1] - start[1]) * frac + self.rng.gauss(0, 3),
        )
        self._emit(
            EventType.PASS,
            team_id=team,
            player_id=carrier,
            related_player_id=receiver,
            start=start,
            end=end,
            outcome=Outcome.FAIL,
            attrs=attrs,
        )
        self._advance(travel * frac, ball_to=(min(max(end[0], 0), PITCH_LENGTH), min(max(end[1], 0), PITCH_WIDTH)))
        ex, ey = end
        rel_end_x, _ = self._rel(team, end)
        if 0 < ey < PITCH_WIDTH and self.rng.random() < 0.21:
            # Overhit or deflected out of play: put it out over the nearest touchline.
            ey = 0.0 if ey < PITCH_WIDTH / 2 else PITCH_WIDTH
        if ey <= 0 or ey >= PITCH_WIDTH:
            self._throw_in(opp, (ex, 0.0 if ey <= 0 else PITCH_WIDTH))
            return
        if rel_end_x > 85 and self.rng.random() < 0.5:
            # Behind for a goal kick, or deflected behind by a defender.
            if self.rng.random() < 0.5:
                self._corner(team)
            else:
                self._goal_kick(opp)
            return
        if rel_end_x >= PITCH_LENGTH or (rel_end_x > 90 and self.rng.random() < 0.6):
            self._goal_kick(opp)
            return
        if rel_end_x <= 0:
            self._corner(opp)
            return
        winner, wd = self._nearest(opp, s.ball)
        if wd < 7 and self.rng.random() < 0.28:
            self._emit(EventType.INTERCEPTION, team_id=opp, player_id=winner, start=s.ball, outcome=Outcome.SUCCESS)
            self._change_possession(opp, winner, "interception")
        else:
            # Loose ball: whoever is closest wins it.
            mate, md = self._nearest(team, s.ball, exclude=carrier)
            if md < wd and self.rng.random() < 0.5:
                s.carrier = mate
            else:
                self._change_possession(opp, winner, "loose_ball")
        self._advance(1.2, chasers=(s.carrier,))

    def _support_run(self, team: str, receiver: str) -> None:
        """A teammate runs off the ball to offer the next pass, and the nearest opponent tracks the run."""
        s = self.s
        runners = [p for p in s.on_pitch[team] if p != receiver and s.roles[p] != "GK" and p not in s.targets]
        if not runners:
            return
        directed = self._intent.directed_run(team, runners, s) if self._intent is not None else None
        if directed is not None:
            # A run the tactic asks for goes first; no random draw is spent on it.
            runner, run_to = directed
        else:
            runner = self.rng.choice(runners)
            rx, ry = self._rel(team, s.positions[runner])
            run_to = self._abs(team, (min(rx + self.rng.uniform(6, 20), PITCH_LENGTH - 4),
                                      min(max(ry + self.rng.gauss(0, 8), 2), PITCH_WIDTH - 2)))
        s.targets[runner] = run_to
        marker, _ = self._nearest(self._opp(team), run_to)
        if s.roles.get(marker) != "GK" and marker not in s.targets:
            mx, my = self._rel(team, run_to)
            s.targets[marker] = self._abs(team, (mx - 2, my))

    def _cross(self, carrier: str, pressured: bool) -> None:
        """A cross from a wide area into the box: usually cleared, sometimes met with a shot."""
        s = self.s
        team = s.possession
        opp = self._opp(team)
        runners = [p for p in s.on_pitch[team] if p != carrier and self._rel(team, s.positions[p])[0] > 72
                   and self.s.roles[p] != "GK"]
        if not runners:
            self._pass(carrier, pressured)
            return
        target = self.rng.choice(runners)
        aim_rel = (self.rng.uniform(88, 97), self.rng.uniform(26, 42))
        aim = self._abs(team, aim_rel)
        start = s.ball
        d = distance(start, aim)
        attrs: dict[str, float | int | str | bool] = {
            "ball_speed_kmh": round(min(max(24 + 1.45 * d + self.rng.gauss(0, 6), 18), 110), 1),
            "height": "high", "pressured": pressured, "cross": True}
        met = self.rng.random() < 0.3 - (0.08 if pressured else 0.0)
        self._emit(EventType.PASS, team_id=team, player_id=carrier, related_player_id=target, start=start,
                   end=aim, outcome=Outcome.SUCCESS if met else Outcome.FAIL, attrs=attrs)
        s.targets[target] = aim
        self._advance(d / 17, ball_to=aim, chasers=(target,))
        if met:
            s.carrier = target
            if self.rng.random() < 0.55:
                self._shot(target, aim_rel, header=self.rng.random() < 0.3, assist=carrier)
            return
        roll = self.rng.random()
        if roll < 0.25:
            self._corner(team)
        elif roll < 0.6:
            self._goal_kick(opp)
        else:
            clearer, _ = self._nearest(opp, aim)
            self._emit(EventType.INTERCEPTION, team_id=opp, player_id=clearer, start=aim, outcome=Outcome.SUCCESS,
                       attrs={"clearance": True})
            cleared_to = self._abs(team, (self.rng.uniform(60, 80), self.rng.uniform(10, 58)))
            self._advance(1.6, ball_to=cleared_to)
            winner_team = team if self.rng.random() < 0.4 else opp
            winner, _ = self._nearest(winner_team, cleared_to)
            if winner_team == team:
                s.carrier = winner
            else:
                self._change_possession(opp, winner, "clearance")

    def _carry(self, carrier: str, pressured: bool) -> None:
        s = self.s
        team = s.possession
        bx, by = self._rel(team, s.ball)
        length = self.rng.uniform(4, 14)
        heading = self.rng.gauss(0, 0.55)
        if bx > 70:
            heading = 0.6 * math.atan2(PITCH_WIDTH / 2 - by, PITCH_LENGTH - bx) + self.rng.gauss(0, 0.35)
        ex = min(bx + length * math.cos(heading), PITCH_LENGTH - 2)
        ey = min(max(by + length * math.sin(heading), 1.5), PITCH_WIDTH - 1.5)
        end = self._abs(team, (ex, ey))
        speed = self.rng.uniform(4.5, self.meta.players[carrier].top_speed * 0.9)
        self._emit(
            EventType.CARRY,
            team_id=team,
            player_id=carrier,
            start=s.ball,
            end=end,
            outcome=Outcome.SUCCESS,
            attrs={"speed_kmh": round(speed * 3.6, 1)},
        )
        self._support_run(team, carrier)
        self._advance(distance(s.ball, end) / speed, ball_to=end, chasers=(carrier,))

    def _shot(
        self,
        shooter: str,
        rel_pos: Vec,
        header: bool = False,
        big_chance: bool = False,
        force: Outcome | None = None,
        credited: str | None = None,
        assist: str | None = None,
        set_piece: str | None = None,
    ) -> None:
        s = self.s
        team = s.possession
        opp = self._opp(team)
        xg = expected_goals(*rel_pos, header=header, big_chance=big_chance)
        if xg >= 0.3:
            big_chance = True
        if header:
            speed = self.rng.uniform(38, 70)
        else:
            speed = min(max(self.rng.gauss(92, 14), 50), 128)
        start = self._abs(team, rel_pos)
        dist_goal, _ = goal_distance_and_angle(*rel_pos)

        if force is not None:
            outcome = force
        else:
            roll = self.rng.random()
            blocked = 0.2 + 0.012 * max(0.0, dist_goal - 10)
            if roll < blocked:
                outcome = Outcome.BLOCKED
            elif roll < blocked + 0.38:
                outcome = Outcome.OFF_TARGET
            else:
                # Goals per shot match xG: P(goal | on target) = xG / P(on target).
                on_target = 1 - blocked - 0.38
                scores = (not self.storyline.scripted_goals_only) and self.rng.random() < min(0.95, xg / on_target)
                outcome = Outcome.GOAL if scores else Outcome.SAVED

        goal_y = 34 + self.rng.uniform(-3.2, 3.2) if outcome in (Outcome.GOAL, Outcome.SAVED) else 34 + self.rng.choice([-1, 1]) * self.rng.uniform(4.2, 9)
        end = self._abs(team, (PITCH_LENGTH, goal_y))
        attrs: dict[str, float | int | str | bool] = {
            "xg": xg,
            "shot_speed_kmh": round(speed, 1),
            "body_part": "head" if header else self.rng.choice(["right_foot", "right_foot", "left_foot"]),
            "big_chance": big_chance,
            "distance_m": round(dist_goal, 1),
        }
        if set_piece:
            attrs["set_piece"] = set_piece
        shot = self._emit(
            EventType.SHOT,
            team_id=team,
            player_id=credited or shooter,
            related_player_id=assist,
            start=start,
            end=end,
            outcome=outcome,
            attrs=attrs,
        )
        travel = dist_goal / (speed / 3.6)
        if self._stop_at is not None:
            # A rollout ends with the first shot; frames still run until the ball is dealt with.
            self._pending_terminal = "goal" if outcome == Outcome.GOAL else "shot"
        if outcome == Outcome.BLOCKED:
            blocker, _ = self._nearest(opp, start)
            block_pt = (start[0] + (end[0] - start[0]) * 0.15, start[1] + (end[1] - start[1]) * 0.15)
            self._advance(0.4, ball_to=block_pt)
            self._rollout_end("shot")
            if self.rng.random() < 0.5:
                self._corner(team)
            else:
                self._change_possession(opp, blocker, "blocked_shot")
                self._advance(1.0)
            return
        try:
            self._advance(travel, ball_to=end)
        except _Stop:
            # The horizon fell mid-flight: a rollout still records the save or goal.
            if outcome not in (Outcome.GOAL, Outcome.SAVED):
                raise
        if outcome == Outcome.OFF_TARGET:
            self._rollout_end("shot")
            self._goal_kick(opp)
            return
        gk = self._player_by_role(opp, ("GK",))
        if outcome == Outcome.SAVED:
            self._emit(EventType.SAVE, team_id=opp, player_id=gk, related_player_id=shooter, start=end,
                       outcome=Outcome.SUCCESS, attrs={"xg_faced": xg, "shot_event_id": shot.event_id})
            self._rollout_end("shot")
            if self.rng.random() < 0.38:
                self._corner(team)
            else:
                s.ball = s.positions[gk]
                self._change_possession(opp, gk, "save")
                self._advance(self.rng.uniform(3, 7))
            return
        # Goal.
        s.score[team] += 1
        goal = self._emit(
            EventType.GOAL,
            team_id=team,
            player_id=credited or shooter,
            related_player_id=assist,
            start=start,
            end=end,
            outcome=Outcome.GOAL,
            attrs={
                "xg": xg,
                "shot_speed_kmh": round(speed, 1),
                "shot_event_id": shot.event_id,
                "home_score": s.score[self.meta.home.team_id],
                "away_score": s.score[self.meta.away.team_id],
            },
        )
        self._rollout_end("goal")
        if credited and credited != shooter:
            delay = self.rng.uniform(40, 80)
            self._pending_corrections.append((s.elapsed + delay, shot, shooter))
            self._pending_corrections.append((s.elapsed + delay, goal, shooter))
        # Celebration and restart: players walk back to kick-off shape.
        s.carrier = ""
        s.targets.update(self._kickoff_positions())
        s.targets[self._player_by_role(opp, ("ST", "CAM", "AM"))] = CENTRE
        self._advance(self.rng.uniform(55, 85), ball_to=CENTRE)
        self._kickoff(opp, reset=False)

    # ----------------------------------------------------------- set pieces

    def _foul(self, offender: str, victim: str, card: Outcome | None = None) -> None:
        s = self.s
        off_team = self._team_of(offender)
        vic_team = self._team_of(victim)
        spot = s.positions.get(victim, s.ball)
        self._emit(EventType.FOUL, team_id=off_team, player_id=offender, related_player_id=victim, start=spot)
        if card is None and self.rng.random() < 0.15 and offender not in s.booked:
            card = Outcome.YELLOW
        if card is not None:
            if card == Outcome.RED and offender in s.booked:
                card = Outcome.SECOND_YELLOW
            self._emit(EventType.CARD, team_id=off_team, player_id=offender, start=spot, outcome=card)
            if card == Outcome.YELLOW:
                s.booked.add(offender)
            else:
                s.sent_off.add(offender)
                s.on_pitch[off_team].remove(offender)
                s.positions.pop(offender, None)
                if s.carrier == offender:
                    s.carrier = ""
        self._rollout_end("restart:foul")
        self._advance(self.rng.uniform(20, 40) + (40 if card else 0), ball_to=spot)
        self._free_kick(vic_team, victim if victim in s.on_pitch[vic_team] else self._nearest(vic_team, spot)[0])

    def _free_kick(self, team: str, taker: str) -> None:
        s = self.s
        if s.possession != team:
            s.possession = team
        s.carrier = taker
        self._emit(EventType.FREE_KICK, team_id=team, player_id=taker, start=s.ball)
        rel = self._rel(team, s.ball)
        dist_goal, angle = goal_distance_and_angle(*rel)
        if dist_goal < 30 and angle > 0.2 and self.rng.random() < 0.35:
            self._shot(taker, rel, set_piece="free_kick")
        else:
            self._pass(taker, False, set_piece="free_kick")

    def _throw_in(self, team: str, spot: Vec) -> None:
        self._rollout_end("restart:throw_in")
        s = self.s
        s.ball = (min(max(spot[0], 1.0), PITCH_LENGTH - 1), spot[1])
        taker, _ = self._nearest(team, s.ball)
        s.possession, s.carrier = team, taker
        self._advance(self.rng.uniform(10, 18), chasers=(taker,))
        self._emit(EventType.THROW_IN, team_id=team, player_id=taker, start=s.ball)
        self._pass(taker, False, set_piece="throw_in")

    def _goal_kick(self, team: str) -> None:
        self._rollout_end("restart:goal_kick")
        s = self.s
        gk = self._player_by_role(team, ("GK",))
        spot = self._abs(team, (5.5, 34 + self.rng.choice([-9, 9])))
        s.carrier = ""
        s.targets[gk] = spot
        self._advance(self.rng.uniform(16, 28), ball_to=spot)
        s.possession, s.carrier = team, gk
        self._emit(EventType.GOAL_KICK, team_id=team, player_id=gk, start=spot)
        self._pass(gk, False, set_piece="goal_kick")

    def _corner(self, team: str) -> None:
        self._rollout_end("restart:corner")
        s = self.s
        opp = self._opp(team)
        flag = self._abs(team, (PITCH_LENGTH, self.rng.choice([0.0, PITCH_WIDTH])))
        taker = self._player_by_role(team, ("LW", "RW", "LAM", "RAM", "CAM", "CM"))
        s.carrier = ""
        s.targets[taker] = flag
        self._advance(self.rng.uniform(22, 34), ball_to=flag)
        s.possession, s.carrier = team, taker
        self._emit(EventType.CORNER, team_id=team, player_id=taker, start=flag)
        targets = [p for p in s.on_pitch[team] if self.meta.players[p].position in (Position.DEF, Position.FWD)
                   and self.s.roles[p] != "GK" and p != taker]
        target = self.rng.choice(targets or s.on_pitch[team])
        aim_rel = (self.rng.uniform(93, 100), self.rng.uniform(28, 40))
        aim = self._abs(team, aim_rel)
        d = distance(flag, aim)
        if self.rng.random() < 0.33:
            s.targets[target] = aim
            self._emit(EventType.PASS, team_id=team, player_id=taker, related_player_id=target, start=flag,
                       end=aim, outcome=Outcome.SUCCESS,
                       attrs={"ball_speed_kmh": round(60 + self.rng.gauss(0, 6), 1), "height": "high",
                              "pressured": False, "set_piece": "corner"})
            self._advance(d / 17, ball_to=aim)
            s.carrier = target
            self._shot(target, aim_rel, header=True, set_piece="corner")
        else:
            self._emit(EventType.PASS, team_id=team, player_id=taker, related_player_id=target, start=flag,
                       end=aim, outcome=Outcome.FAIL,
                       attrs={"ball_speed_kmh": round(60 + self.rng.gauss(0, 6), 1), "height": "high",
                              "pressured": False, "set_piece": "corner"})
            self._advance(d / 17, ball_to=aim)
            clearer, _ = self._nearest(opp, aim)
            self._emit(EventType.INTERCEPTION, team_id=opp, player_id=clearer, start=aim, outcome=Outcome.SUCCESS,
                       attrs={"clearance": True})
            cleared_to = self._abs(team, (self.rng.uniform(65, 80), self.rng.uniform(10, 58)))
            self._advance(1.6, ball_to=cleared_to)
            winner_team = team if self.rng.random() < 0.45 else opp
            winner, _ = self._nearest(winner_team, cleared_to)
            if winner_team == team:
                s.carrier = winner
            else:
                self._change_possession(opp, winner, "clearance")

    def _kickoff(self, team: str, reset: bool = True) -> None:
        s = self.s
        striker = self._player_by_role(team, ("ST", "CAM", "AM"))
        if reset:
            self._reset_positions()
            s.positions[striker] = CENTRE
        s.ball = CENTRE
        s.possession, s.carrier = team, striker
        self._emit(EventType.KICKOFF, team_id=team, player_id=striker, start=CENTRE)
        self._advance(1.0)
        self._pass(striker, False)

    # --------------------------------------------------------------- beats

    def _take_possession(self, team: str) -> None:
        s = self.s
        if s.possession == team and s.carrier in s.on_pitch[team]:
            return
        winner, _ = self._nearest(team, s.ball)
        self._emit(EventType.INTERCEPTION, team_id=team, player_id=winner, start=s.ball, outcome=Outcome.SUCCESS)
        self._change_possession(team, winner, "interception")
        self._advance(1.0, chasers=(winner,))

    def _build_up(self, team: str, final_passer: str | None, shooter: str, shot_rel: Vec) -> None:
        """Two to four successful passes that work the ball to the shooter."""
        s = self.s
        chain: list[str] = []
        mids = [p for p in s.on_pitch[team] if self.meta.players[p].position == Position.MID
                and p not in (shooter, final_passer, s.carrier)]
        self.rng.shuffle(mids)
        chain.extend(mids[: self.rng.randint(1, 2)])
        if final_passer and final_passer != s.carrier:
            chain.append(final_passer)
        chain.append(shooter)
        waypoints = {
            shooter: shot_rel,
            final_passer or "": (self.rng.uniform(80, 92), self.rng.uniform(8, 60)),
        }
        x_rel = self._rel(team, s.ball)[0]
        for receiver in chain:
            if receiver in waypoints:
                target_rel = waypoints[receiver]
            else:
                x_rel = min(max(x_rel + self.rng.uniform(10, 22), 50), 82)
                target_rel = (x_rel, self.rng.uniform(15, 53))
            target = self._abs(team, target_rel)
            s.targets[receiver] = target
            d = distance(s.ball, target)
            speed_kmh = round(min(max(24 + 1.45 * d + self.rng.gauss(0, 6), 18), 110), 1)
            self._emit(EventType.PASS, team_id=team, player_id=s.carrier, related_player_id=receiver,
                       start=s.ball, end=target, outcome=Outcome.SUCCESS,
                       attrs={"ball_speed_kmh": speed_kmh, "height": "high" if d > 30 else "ground",
                              "pressured": self.rng.random() < 0.3})
            s.carrier = receiver
            self._advance(d / (speed_kmh / 3.6 * 0.85) + self.rng.uniform(0.5, 1.4), ball_to=target,
                          chasers=(receiver,))

    def _play_beat(self, beat: Beat) -> None:
        s = self.s
        team = beat.team_id
        if beat.type in (BeatType.GOAL, BeatType.BIG_CHANCE):
            if beat.player_id not in s.on_pitch[team]:
                return
            self._take_possession(team)
            shot_rel = (self.rng.uniform(91, 97), self.rng.uniform(28, 40))
            assist = beat.related_player_id if beat.related_player_id in s.on_pitch[team] else None
            self._build_up(team, assist, beat.player_id, shot_rel)
            if beat.type == BeatType.GOAL:
                self._shot(beat.player_id, shot_rel, big_chance=True, force=Outcome.GOAL,
                           credited=beat.initially_credited_to, assist=assist)
            else:
                force = self.rng.choice([Outcome.SAVED, Outcome.OFF_TARGET])
                self._shot(beat.player_id, shot_rel, big_chance=True, force=force)
        elif beat.type in (BeatType.YELLOW_CARD, BeatType.RED_CARD):
            if beat.player_id not in s.on_pitch[team]:
                return
            opp = self._opp(team)
            victim, _ = self._nearest(opp, s.positions[beat.player_id])
            card = Outcome.YELLOW if beat.type == BeatType.YELLOW_CARD else Outcome.RED
            self._foul(beat.player_id, victim, card=card)
        elif beat.type == BeatType.SUBSTITUTION:
            off, on = beat.player_id, beat.related_player_id
            if not on or off not in s.on_pitch[team]:
                return
            self._advance(self.rng.uniform(20, 35))
            idx = s.on_pitch[team].index(off)
            s.on_pitch[team][idx] = on
            s.roles[on] = s.roles[off]
            touchline = (52.5, 0.5)
            s.positions.pop(off, None)
            s.positions[on] = touchline
            if s.carrier == off:
                s.carrier = on
            self._emit(EventType.SUBSTITUTION, team_id=team, player_id=off, related_player_id=on,
                       start=touchline)

    # ----------------------------------------------------------------- run

    def _schedule(self) -> list[_Scheduled]:
        out = []
        for beat in self.storyline.beats:
            period = 1 if beat.minute <= 45 else 2
            clock = (beat.minute - 1) * 60 + self.rng.uniform(2, 20)
            out.append(_Scheduled(beat=beat, period=period, clock=clock))
        return out

    def _play_period(
        self,
        period: int,
        kickoff_team: str,
        end_clock: float,
        schedule: list[_Scheduled],
        pause_at: float | None = None,
    ) -> None:
        s = self.s
        s.period = period
        s.clock = HALF_LENGTH * (period - 1)
        self._kickoff(kickoff_team)
        while s.clock < end_clock:
            if pause_at is not None and s.elapsed >= pause_at:
                return  # stopped at a clean step boundary, ready to be snapshotted
            due = [b for b in schedule if b.period == period and b.clock <= s.clock]
            if due:
                item = due[0]
                schedule.remove(item)
                self._play_beat(item.beat)
                continue
            if not s.carrier or s.carrier not in s.on_pitch.get(s.possession, []):
                self._take_possession(s.possession or kickoff_team)
            self._step()
        self._emit(EventType.HALF_TIME if period == 1 else EventType.FULL_TIME,
                   attrs={"home_score": s.score[self.meta.home.team_id],
                          "away_score": s.score[self.meta.away.team_id]})

    def run_until(self, elapsed: float) -> None:
        """Play the first half up to the first step boundary at or after ``elapsed`` seconds, then stop there
        (a state that can be snapshotted and resumed). The match is not finished: use run() for that."""
        self._setup()
        schedule = self._schedule()
        self._play_period(1, self.meta.home.team_id, HALF_LENGTH, schedule, pause_at=elapsed)

    # ---------------------------------------------------------------- forking

    def snapshot(self) -> SimSnapshot:
        """Freeze the simulator at a step boundary so it can be resumed or forked (see simulator/fork.py)."""
        from matchlens.simulator.fork import take_snapshot

        return take_snapshot(self)

    @classmethod
    def resume(
        cls,
        snap: SimSnapshot,
        *,
        seed: int | None = None,
        styles: dict[str, SimStyle] | None = None,
        intent: IntentController | None = None,
        frame_dt: float = 1.0,
        id_prefix: str = "fork-",
    ) -> MatchSimulator:
        """A simulator that continues from a snapshot. seed=None restores the random stream exactly;
        otherwise a fresh Random(seed) drives the continuation."""
        from matchlens.simulator.fork import restore

        return restore(snap, seed=seed, styles=styles, intent=intent, frame_dt=frame_dt, id_prefix=id_prefix)

    def rollout(self, horizon_s: float) -> RolloutTrace:
        """Play on for up to ``horizon_s`` seconds, stopping early at the first shot, goal, turnover or
        dead ball. Consumes this simulator: fork again from a snapshot for another rollout."""
        from matchlens.simulator.fork import run_rollout

        return run_rollout(self, horizon_s)

    def run(self) -> SyntheticMatch:
        self._setup()
        schedule = self._schedule()
        home, away = self._team_ids()
        last_p1 = max((b.clock for b in schedule if b.period == 1), default=0)
        last_p2 = max((b.clock for b in schedule if b.period == 2), default=0)
        end1 = max(HALF_LENGTH + 60 * self.rng.randint(1, 3), last_p1 + 90)
        end2 = max(2 * HALF_LENGTH + 60 * self.rng.randint(3, 5), last_p2 + 90)
        self._play_period(1, home, end1, schedule)
        self._play_period(2, away, end2, schedule)
        # Any correction still pending at full time is issued immediately.
        for item in list(self._pending_corrections):
            self._pending_corrections.remove(item)
            self._pending_corrections.append((self.s.elapsed, item[1], item[2]))
        self._flush_corrections()
        return SyntheticMatch(meta=self.meta, events=self.events, tracking=self.tracking, seed=self.seed)


def generate_match(seed: int = 7, storyline: Storyline | None = None) -> SyntheticMatch:
    return MatchSimulator(seed=seed, storyline=storyline).run()
