"""Author the replacement film from retained speech and three new human takes."""
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = json.loads((ROOT / "story-v2.json").read_text())
audio_dir = ROOT / "public/audio/v2"
audio_dir.mkdir(parents=True, exist_ok=True)
original = ROOT / "public/audio/pl-demo-hackathon-original.m4a"
transcript = json.loads((ROOT / "out/voice-transcript-original.json").read_text())
original_words = [dict(w) for s in transcript["segments"] for w in s["words"]]
corrections = {120:" goalscorer",121:".",124:" affected",233:" the",234:" score",235:"line,"}
for i,w in enumerate(original_words):
    w["word"] = corrections.get(i,w["word"])

cursor = 0
timeline = []
captions = {}
voice = {}
pending = []
for scene in spec["scenes"]:
    sid = scene["id"]
    entry = {**scene,"startFrame":cursor,"durationInFrames":scene["frames"]}
    timeline.append(entry)
    cursor += scene["frames"]
    duration = scene["frames"] / spec["fps"]
    target = audio_dir / f"{sid}.wav"
    if scene.get("replacement"):
        raw = next((audio_dir/f"{sid}-raw{ext}" for ext in (".m4a",".wav",".mp3") if (audio_dir/f"{sid}-raw{ext}").exists()),None)
        aligned = audio_dir/f"{sid}-transcript.json"
        if raw is None or not aligned.exists():
            pending.append(sid)
            captions[sid] = []
            continue
        data = json.loads(aligned.read_text())
        words = [w for s in data["segments"] for w in s["words"]]
        ranges = [(max(0,words[0]["start"]-.15),min(data["duration"],words[-1]["end"]+.25))]
        source = raw
    else:
        source = original
        words = original_words
        ranges = scene["sourceRanges"]
    length = sum(b-a for a,b in ranges)
    if length > duration + .005:
        raise ValueError(f"{sid}: speech is {length:.2f}s but scene is {duration:.2f}s; retime rather than clip")
    filters = []
    local = []
    offset = 0
    for index,(start,end) in enumerate(ranges):
        for w in words:
            if w["start"] < end and w["end"] > start:
                if w["start"] < start or w["end"] > end:
                    raise ValueError(f"{sid}: edit intersects spoken word {w['word']}")
                local.append({"text":w["word"],"startMs":round((offset+w["start"]-start)*1000),"endMs":round((offset+w["end"]-start)*1000),"timestampMs":round((offset+w["start"]-start)*1000),"confidence":w["probability"]})
        d = end-start
        filters.append(f"[0:a]atrim=start={start}:end={end},asetpts=PTS-STARTPTS,afade=t=in:d=0.006,afade=t=out:st={d-.006}:d=0.006[a{index}]")
        offset += d
    filters.append("".join(f"[a{i}]" for i in range(len(ranges)))+f"concat=n={len(ranges)}:v=0:a=1,highpass=f=65,loudnorm=I=-16:TP=-1.5:LRA=11,aresample=48000,apad=whole_dur={duration}[a]")
    subprocess.run(["ffmpeg","-v","error","-y","-i",str(source),"-filter_complex",";".join(filters),"-map","[a]","-t",str(duration),"-c:a","pcm_s24le",str(target)],check=True)
    captions[sid] = local
    voice[sid] = f"audio/v2/{sid}.wav"

if cursor/spec["fps"] >= spec["maxSeconds"]:
    raise ValueError("The film must be shorter than the hackathon limit")
(audio_dir/"captions.json").write_text(json.dumps(captions,indent=2))
generated = {"fps":spec["fps"],"frames":cursor,"scenes":timeline,"voice":voice,"captions":captions,"pending":pending}
(ROOT/"out/v2").mkdir(parents=True,exist_ok=True)
(ROOT/"out/v2/edit.json").write_text(json.dumps(generated,indent=2))
(ROOT/"src/v2-timeline.ts").write_text("// Generated by scripts/prepare-v2.py; narration stays local.\nexport const v2 = "+json.dumps(generated,indent=2)+" as const;\n")
print(f"Replacement cut: {cursor/spec['fps']:.2f}s; {len(voice)}/{len(timeline)} voice clips; pending: {', '.join(pending) or 'none'}")
