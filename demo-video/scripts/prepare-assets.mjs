import { readdir, writeFile, mkdir, readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve, dirname } from "node:path";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = async (dir) => {
  await mkdir(`${root}/public/${dir}`, { recursive: true });
  return readdir(`${root}/public/${dir}`);
};
const names = [
  "opening",
  "introduction",
  "evidence",
  "replay",
  "agents",
  "correction",
  "multiverse",
  "pundit",
  "catchup",
  "winner",
];
const footageFiles = await read("footage");
const audioFiles = await read("audio");
const footage = Object.fromEntries(
  names.flatMap((id, i) => {
    const prefix = String(i + 1).padStart(2, "0") + "-";
    const file =
      footageFiles.find(
        (f) =>
          f.startsWith(prefix) &&
          f.includes("-detail.") &&
          /\.(mp4|webm|mov)$/i.test(f),
      ) ??
      footageFiles.find(
        (f) =>
          f.startsWith(prefix) &&
          !/multiverse-[1-4]\./.test(f) &&
          /\.(mp4|webm|mov)$/i.test(f),
      );
    return file ? [[id, `footage/${file}`]] : [];
  }),
);
for (let i = 1; i <= 4; i++)
  if (footageFiles.includes(`07-multiverse-${i}.mp4`))
    footage[`multiverse${i}`] = `footage/07-multiverse-${i}.mp4`;
const voiceNames = [
  "opening",
  "introduction",
  "evidence",
  "agents",
  "correction",
  "multiverse",
  "pundit",
  "platform",
  "closing",
];
const voice = Object.fromEntries(
  voiceNames.flatMap((id, i) => {
    const prefix = String(i + 1).padStart(2, "0") + "-";
    const file = audioFiles.find(
      (f) => f.startsWith(prefix) && /\.(wav|mp3|m4a|aac)$/i.test(f),
    );
    return file ? [[id, `audio/${file}`]] : [];
  }),
);
await writeFile(
  `${root}/src/media-manifest.ts`,
  `// Generated by scripts/prepare-assets.mjs. Media files remain local.\nexport const footage: Record<string, string> = ${JSON.stringify(footage, null, 2)};\nexport const voice: Record<string, string> = ${JSON.stringify(voice, null, 2)};\n`,
);
await writeFile(
  `${root}/public/asset-manifest.local.json`,
  JSON.stringify({ footage, voice }, null, 2),
);
const guideTiming = [
  ["opening", 0, 9],
  ["introduction", 9, 13],
  ["evidence", 22, 14],
  ["agents", 36, 16],
  ["correction", 52, 12],
  ["multiverse", 64, 18],
  ["pundit", 82, 15],
  ["platform", 97, 12],
  ["closing", 109, 6],
];
let timing = guideTiming.map(([id, start, duration]) => ({
  id,
  startFrame: start * 30,
  durationInFrames: duration * 30,
}));
try {
  timing = JSON.parse(
    await readFile(`${root}/public/audio/voice-timing.json`, "utf8"),
  );
} catch (e) {
  if (e.code !== "ENOENT") throw e;
}
let captionData = {};
try {
  captionData = JSON.parse(
    await readFile(`${root}/public/audio/captions-reviewed.json`, "utf8"),
  );
} catch (e) {
  if (e.code !== "ENOENT") throw e;
}
const nodes = timing
  .map(
    ({ id, startFrame, durationInFrames }) =>
      `<Sequence name="${id} voice captions" ${startFrame ? `from={${startFrame}}` : ""} durationInFrames={${durationInFrames}}><BasicCaptions name="${id} subtitles" width={3000} style={{position:'absolute',bottom:78,left:210,scale:0.5,transformOrigin:'bottom left'}} captions={${JSON.stringify(captionData[id] ?? [])}} /></Sequence>`,
  )
  .join("\n");
await writeFile(
  `${root}/src/VoiceCaptions.tsx`,
  `// Generated from human voice transcripts; times are local to each scene.\nimport {Sequence,Track} from 'remotion';\nimport {BasicCaptions} from './basic-captions';\nexport const VoiceCaptions=()=>{return <Track name="Human voice captions">${nodes}</Track>;};\n`,
);
console.log(
  `${names.filter((n) => footage[n]).length}/10 product clips, ${Object.keys(footage).filter((n) => n.startsWith("multiverse") && n !== "multiverse").length} perspective crops; ${Object.keys(voice).length}/9 narration segments.`,
);
